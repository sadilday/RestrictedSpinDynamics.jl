# Rank-resolved dynamical Lie algebra for the higher-spin (spherical-tensor) representation.
# DLA classification / grade-closure floor: Wiersema, Kokcu, Kemper, Bakalov, npj Quantum Information 10, 110
# (2024); Kokcu, Wiersema, Kemper, Bakalov, J. Math. Phys. 67, 052205 (2026).

# Generic pivoted-elimination span / Lie closure over label-indexed complex vectors. A tensor commutator
# (top_comm) is a SUM of labels, so unlike the monomial Pauli DLA (a set count in basis.jl) this is a genuine
# subspace: close it by pivoted Gaussian elimination. Complex span = real DLA dimension, since the complexified
# L_C = L ⊕ iL has anti-Hermitian L and Hermitian iL meeting only at 0 (dim_C L_C = dim_R L); no real conversion.
# _dla_addop!: reduce `op0` against the echelon `basis`; append the normalized residual if nonzero, return whether added.
function _dla_addop!(basis::Vector{D}, piv::Dict{L,Int}, op0; tol::Float64) where {L,D<:AbstractDict{L,ComplexF64}}
    op = D(k => ComplexF64(v) for (k, v) in op0 if abs(v) > tol)
    while !isempty(op)
        p = maximum(keys(op))
        if haskey(piv, p)
            b = basis[piv[p]]; f = op[p] / b[p]
            for (k, v) in b
                op[k] = get(op, k, zero(ComplexF64)) - f * v
            end
            for k in collect(keys(op))
                abs(op[k]) <= tol && delete!(op, k)
            end
        else
            f = op[p]
            for k in keys(op)
                op[k] /= f
            end
            push!(basis, op); piv[p] = length(basis)
            return true
        end
    end
    return false
end

# Span dimension (real rank over the complexified space) of a list of operators.
function _span_rank(ops::Vector{D}; tol::Float64 = 1e-9) where {L,D<:AbstractDict{L,ComplexF64}}
    basis = D[]; piv = Dict{L,Int}()
    for o in ops
        _dla_addop!(basis, piv, o; tol = tol)
    end
    return length(basis)
end

# Close the Lie algebra generated by `seeds` under `bracket`; return (echelon basis, capped::Bool).
function _lie_closure(seeds::Vector{D}, bracket; maxdim::Int = 20000, tol::Float64 = 1e-9) where {L,D<:AbstractDict{L,ComplexF64}}
    basis = D[]; piv = Dict{L,Int}(); q = Int[]
    for g in seeds
        _dla_addop!(basis, piv, g; tol = tol) && push!(q, length(basis))
    end
    while !isempty(q)
        i = popfirst!(q); j = 1
        while j <= length(basis)
            if j != i
                length(basis) > maxdim && return (basis, true)
                _dla_addop!(basis, piv, bracket(basis[i], basis[j]); tol = tol) && push!(q, length(basis))
            end
            j += 1
        end
    end
    return (basis, false)
end

# strip the identity component: it commutes with everything and the DLA lives in the traceless algebra.
_strip_id(op::TensorDict{B}) where {B} = TensorDict{B}(k => v for (k, v) in op if k != spin_tensor_id(B))
# distinct labels carrying nonzero weight across a set of operators
function _support_labels(ops::Vector{TensorDict{B}}; tol::Float64 = 1e-9) where {B}
    s = Set{SpinTensorLabel{B}}()
    for o in ops, (k, v) in o
        abs(v) > tol && push!(s, k)
    end
    return collect(s)
end
# filtration dims: dim(DLA ∩ {measure(label) <= m}) for m in 0:mmax, via rank-nullity on the >m projection.
function _filtration(basis::Vector{TensorDict{B}}, dim::Int, measure, mmax::Int; tol::Float64) where {B}
    return [dim - _span_rank([TensorDict{B}(k => v for (k, v) in row if measure(k) > m) for row in basis]; tol = tol)
            for m in 0:mmax]
end

# Higher-spin (tensor) DLA dimension: the radix twin of the Pauli dla_dimension (documented in basis.jl);
# generators as TensorDicts over `radix`, closed under top_comm; reduces to the Pauli count at d=2.
function dla_dimension(N::Int, generators::Vector{TensorDict{B}}, radix::_RadixArg;
                       maxdim::Int = 20000, tol::Float64 = 1e-9) where {B}
    rad = _radvec(radix, N); tabs = _site_tables(rad)
    seeds = filter(!isempty, [_strip_id(g) for g in generators])
    basis, _ = _lie_closure(seeds, (A, C) -> top_comm(A, C, N, tabs); maxdim = maxdim, tol = tol)
    return length(basis)
end

"""
    dla_report(N, generators, radix; maxdim=20000, tol=1e-9) -> NamedTuple
    dla_report(N, generators::Vector{PauliLabel}) -> NamedTuple

Rank-resolved report on the dynamical Lie algebra generated by `generators` (see [`dla_dimension`](@ref)).
The higher-spin form takes the terms as `TensorDict`s over `radix`; a spin-1/2 `PauliLabel` twin is provided
so the report reads uniformly. Fields:

- `dim`: the DLA dimension.
- `grade_floor`: the smallest `kmax` for which grade truncation is exact (max grade over the algebra).
- `rank_ceiling`: the highest per-site multipole rank reached; `gen_rank`: the max rank in the generators;
  `rank_bounded = (rank_ceiling == gen_rank)` is `false` when commutators climbed the rank ladder (only
  possible for spin >= 3/2, where `[rank-2, rank-2]` opens rank-3).
- `grade_dims[m+1]` = `dim(DLA ∩ {grade <= m})` for `m = 0:N`; `rank_dims[r+1]` = `dim(DLA ∩ {rank <= r})`
  for `r = 0:max(2S)`: the grade and rank filtrations (shell profiles).
- `capped`: whether the `maxdim` safety cap was hit before closure.

See [Higher-Spin](@ref).
"""
function dla_report(N::Int, generators::Vector{TensorDict{B}}, radix::_RadixArg;
                    maxdim::Int = 20000, tol::Float64 = 1e-9) where {B}
    rad = _radvec(radix, N); tabs = _site_tables(rad)
    seeds = filter(!isempty, [_strip_id(g) for g in generators])
    basis, capped = _lie_closure(seeds, (A, C) -> top_comm(A, C, N, tabs); maxdim = maxdim, tol = tol)
    dim = length(basis)
    labels = _support_labels(basis; tol = tol)
    grade_floor  = isempty(labels) ? 0 : maximum(st_grade(l) for l in labels)
    rank_ceiling = isempty(labels) ? 0 : maximum(st_maxrank(l, tabs) for l in labels)
    genlabels = _support_labels(seeds; tol = tol)
    gen_rank = isempty(genlabels) ? 0 : maximum(st_maxrank(l, tabs) for l in genlabels)
    rmax = maximum(rad) - 1                                        # max multipole rank = 2S over sites
    grade_dims = _filtration(basis, dim, st_grade, N; tol = tol)
    rank_dims  = _filtration(basis, dim, l -> st_maxrank(l, tabs), rmax; tol = tol)
    return (; dim, grade_floor, rank_ceiling, gen_rank, rank_bounded = rank_ceiling == gen_rank,
            grade_dims, rank_dims, capped)
end

function dla_report(N::Int, generators::Vector{PauliLabel})
    seen = Set{PauliLabel}(generators)                            # Pauli DLA is monomial (single-string comms)
    frontier = collect(seen)
    while !isempty(frontier)
        newp = PauliLabel[]; snap = collect(seen)
        for a in frontier, b in snap
            r, c = pauli_comm(a, b, N)
            c == 0 && continue
            r in seen || (push!(seen, r); push!(newp, r))
        end
        frontier = newp
    end
    dim = length(seen)
    grade_floor = isempty(seen) ? 0 : maximum(grade(s, N) for s in seen)
    grade_dims = [count(s -> grade(s, N) <= m, seen) for m in 0:N]
    return (; dim, grade_floor, rank_ceiling = (dim > 0 ? 1 : 0), gen_rank = (dim > 0 ? 1 : 0),
            rank_bounded = true, grade_dims, rank_dims = [0, dim], capped = false)  # spin-1/2: rank is trivially 1
end
